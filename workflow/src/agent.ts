/**
 * Agent: URL + goal → reviewable YAML demo script.
 *
 *   npm run agent -- https://transcribe.com/zh/formats-to-mp3 --goal "演示如何把音频转成 MP3"
 *   npm run agent -- <url> --goal "..." -o scripts/out.yaml
 *
 * Uses OPENAI_API_KEY (or OPENROUTER_API_KEY) when set; otherwise heuristic fallback.
 */

import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { stringify as toYaml } from "yaml";
import { loadEnvFile } from "./loadEnv.js";
import { generateDemoScript } from "./script/generateScript.js";
import { collectPageContext } from "./script/pageContext.js";

loadEnvFile();

function parseArgs(argv: string[]) {
	const args = argv.slice(2);
	let url = "";
	let goal = "";
	let out = "";
	let headed = false;

	for (let i = 0; i < args.length; i++) {
		const a = args[i];
		if (a === "--goal" || a === "-g") goal = args[++i] ?? "";
		else if (a === "--out" || a === "-o") out = path.resolve(args[++i] ?? "");
		else if (a === "--headed") headed = true;
		else if (a === "--help" || a === "-h") {
			console.log(`Usage: npm run agent -- <url> --goal "<what to demo>" [-o scripts/out.yaml]

Env:
  OPENAI_API_KEY / OPENROUTER_API_KEY / TRACEVIDS_API_KEY
  OPENAI_BASE_URL   (optional OpenAI-compatible endpoint)
  TRACEVIDS_MODEL   (default gpt-4o-mini or openai/gpt-4o-mini on OpenRouter)
`);
			process.exit(0);
		} else if (!a.startsWith("-")) url = a;
	}

	if (!url) throw new Error("URL required. See --help.");
	new URL(url);
	if (!goal.trim()) {
		goal = "用 20 秒演示这个页面的核心功能，突出主 CTA";
	}
	if (!out) {
		const host = new URL(url).hostname.replace(/\W+/g, "-");
		out = path.resolve("scripts", `${host}.agent.yaml`);
	}
	return { url, goal: goal.trim(), out, headed };
}

async function main() {
	const { url, goal, out, headed } = parseArgs(process.argv);
	console.log(`[agent] url=${url}`);
	console.log(`[agent] goal=${goal}`);

	const context = await collectPageContext(url, headed);
	console.log(`[agent] page title=${context.h1 || context.title}`);
	console.log(`[agent] buttons=${context.buttons.slice(0, 6).join(" | ") || "(none)"}`);

	const { script, mode } = await generateDemoScript({ url, goal, context });
	console.log(`[agent] mode=${mode}`);

	await mkdir(path.dirname(out), { recursive: true });
	const yaml = toYaml(script);
	await writeFile(out, `# Generated by TraceVids agent (${mode})\n# Goal: ${goal}\n# Review before recording.\n${yaml}`, "utf8");

	console.log(`[agent] wrote ${out}`);
	console.log(`[agent] steps=${script.steps.length} captions=${script.captions?.length ?? 0}`);
	console.log(`[agent] next: npm run demo -- --script ${path.relative(process.cwd(), out)}`);
}

main().catch((err) => {
	console.error(err instanceof Error ? err.message : err);
	process.exit(1);
});
